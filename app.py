# قسنا مع النموذج الحقيقي: عبارة موجودة حرفيًا داخل جزء طويل تأخذ تشابهًا شبه صفري،
# مثل "كظم الغيظ والعفو" مع جزء 3:134 الذي فيه "والكاظمين الغيظ والعافين عن الناس"
# (0.06)، بينما "إن الله كان عفوا غفورا" القصيرة تأخذ 0.59. النموذج يقرّب الاستعلام
# القصير من النص القصير. الحل: نوافذ من WINDOW_WORDS كلمات داخل كل جزء أطول منها،
# والآية تأخذ أعلى تشابه بين أجزائها ونوافذها.
WINDOW_WORDS = 6
WINDOW_STRIDE = 3
SHORT_PENALTY = 0.3   # يُطرح من تشابه الأجزاء القصيرة (أقل من 3 كلمات) حين تكون كل ما في الآية
WINDOW_PENALTY = 0.15  # يُطرح من تشابه النافذة قبل مقارنته بتشابه الجزء الكامل
# النتيجة المقاسة (استعلامات حقيقية): النوافذ لم تحسّن التقييم — عقوبة 0 أنزلت P@10 من 0.812
# إلى 0.731 (نصوص قصيرة أكثر = تطابقات زائفة أكثر)، وعقوبة 0.15 تعادل عدم استخدامها. لذلك ملف
# window_embeddings.npy غير مرفوع، والكود يعمل بدونها؛ نبقيه لمن يريد إعادة التجربة.


def make_windows(segments_df: pd.DataFrame) -> pd.DataFrame:
    """نوافذ متداخلة داخل الأجزاء الأطول من WINDOW_WORDS كلمة (نفس الترتيب دائمًا)."""
    rows = []
    for seg_idx, text in enumerate(segments_df["text"]):
        words = str(text).split()
        if len(words) <= WINDOW_WORDS:
            continue
        starts = list(range(0, len(words) - WINDOW_WORDS + 1, WINDOW_STRIDE))
        if starts[-1] != len(words) - WINDOW_WORDS:
            starts.append(len(words) - WINDOW_WORDS)
        for st_ in starts:
            rows.append((seg_idx, " ".join(words[st_:st_ + WINDOW_WORDS])))
    return pd.DataFrame(rows, columns=["segment", "text"])


def _parse_morphology(path: str) -> dict:
    words = {}
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if not line or line[0] == "#":
                continue
            parts = line.split("\t")
            if len(parts) != 4:
                continue
            loc, form, pos, feats = parts
            s, a, w, _seg = loc.split(":")
            key = (int(s), int(a), int(w))
            d = words.get(key)
            if d is None:
                d = words[key] = {"full": "", "root": None, "lemma": None, "vf": None, "stem": None,
                                  "noun": False}
            d["full"] += form
            f = feats.split("|")
            root = lem = vf = None
            for x in f:
                if x.startswith("ROOT:"):
                    root = x[5:]
                elif x.startswith("LEM:"):
                    lem = x[4:]
                elif x.startswith("VF:"):
                    vf = x[3:]
            is_affix = "PREF" in f or "SUFF" in f
            if root is None and "PN" in f and lem:
                root = "PN:" + lem          # أسماء الأعلام بلا جذر: كل اسم "جذر" نفسه
            if root and d["root"] is None:
                d["root"], d["lemma"], d["vf"], d["stem"] = root, lem, vf, form
                d["noun"] = pos == "N"
            elif d["stem"] is None and not is_affix:
                d["stem"] = form
    return words


def _guess_form(word_key: str, root: str, root_forms: dict):
    """يستنتج الوزن الفعلي (II-X) للمصدر من وزنه الصرفي القياسي: تفعيل=II،
    إفعال=IV، تفعُّل=V، تفاعُل=VI، انفعال=VII، افتعال=VIII، استفعال=X،
    وفِعال/مُفاعَلة=III. يُقبل فقط إذا كان هذا الوزن موجودًا فعلًا لهذا الجذر في
    القرآن. مثال: "تحريم" ← حرّم (II) فتطابق "حرّم الربا" ولا تطابق "المسجد
    الحرام"؛ "الجهاد" ← جاهد (III) فتطابق "جاهدوا" ولا تطابق "جَهد أيمانهم"."""
    rk = lex_key(root)
    if len(rk) != 3:
        return None
    a, b, c = rk
    patterns = [
        ("اي" + b + "ا" + c, "4"),        # إفعال من جذر مهموز الأول: إيثار (أثر)، إيمان (أمن)
        ("ت" + a + b + "ي" + c, "2"),
        ("است" + a + b + "ا" + c, "10"),
        ("ا" + a + "ت" + b + "ا" + c, "8"),
        ("ان" + a + b + "ا" + c, "7"),
        ("ا" + a + b + "ا" + c, "4"),
        ("ت" + a + "ا" + b + c, "6"),
        ("ت" + a + b + c, "5"),
        ("م" + a + "ا" + b + c + "ه", "3"),
        (a + b + "ا" + c, "3"),
    ]
    forms = root_forms.get(root, set())
    for pat, form in patterns:
        if word_key == pat and form in forms:
            return form
    return None


def build_lexicon(verses_df: pd.DataFrame, path: str = MORPH_FILE) -> Lexicon:
    raw = _parse_morphology(path)
    vidx = {(int(s), int(a)): i for i, (s, a) in enumerate(zip(verses_df["sura"], verses_df["aya"]))}

    # توحيد مداخل معجمية متكررة بصيغتين في البيانات (مثال: "والِدَي" و"والِد").
    lemmas_by_root = {}
    for d in raw.values():
        if d["root"]:
            lemmas_by_root.setdefault(d["root"], set()).add(d["lemma"])
    lemma_fix = {}
    for r, lems in lemmas_by_root.items():
        for l in lems:
            if l and l.endswith("َي") and l[:-2] in lems:
                lemma_fix[(r, l)] = l[:-2]
        # نفس الكلمة بتاء مفتوحة مرة ومربوطة مرة: "أَمانَت" (33:72) و"أَمانَة" (4:58، 23:8)؛
        # بدون التوحيد كان بحث "الأمانة" لا يطابق آية "تؤدوا الأمانات" إلا بالجذر.
        by_key = {lex_key(l): l for l in lems if l}
        for l in lems:
            k = lex_key(l) if l else ""
            # l.endswith("ت") بلا حركة: يستبعد أفعالًا مثل "عَقَدَتْ" و"دُكَّتِ"
            if l and l.endswith("ت") and k[:-1] + "ه" in by_key:
                lemma_fix[(r, l)] = by_key[k[:-1] + "ه"]

    w_verse, w_pos, w_root, w_lemma, w_vf, w_form = [], [], [], [], [], []
    surface = {}
    root_forms = {}
    for (s, a, w), d in raw.items():
        if not d["root"] or (s, a) not in vidx:
            continue
        r = d["root"]
        l = lemma_fix.get((r, d["lemma"]), d["lemma"])
        l = _nfc(l)
        vf = d["vf"]
        w_verse.append(vidx[(s, a)])
        w_pos.append(w)
        w_root.append(r)
        w_lemma.append(l)
        w_vf.append(vf)
        w_form.append(d["full"])
        if vf:
            root_forms.setdefault(r, set()).add(vf)
        analysis = (r, l, vf, d["noun"])
        keys = set()
        for t in (d["full"], d["stem"] or "", l or ""):
            if t:
                keys.add(lex_key(t, True))
                keys.add(lex_key(t, False))
        for k in keys:
            if len(k) >= 2:
                surface.setdefault(k, Counter())[analysis] += 1

    lex = Lexicon()
    lex.n_verses = len(verses_df)
    lex.w_verse = np.array(w_verse, dtype=np.int32)
    lex.w_pos = np.array(w_pos, dtype=np.int32)
    lex.w_root = w_root
    lex.w_lemma = w_lemma
    lex.w_vf = w_vf
    lex.w_form = w_form
    lex.surface = surface
    # نسخة بلا همزة للبحث الاحتياطي: "القرآن" يكتبها المستخدم "القران"، والرسم
    # العثماني "ٱلْقُرْءَان" مفتاحه "القرءان"؛ بدون هذا طابقت "القران" الجذر قرر
    # (وقرن في بيوتكن، وقري عينا).
    surface_nh = {}
    for k, cnt in surface.items():
        nk = _no_hamza(k)
        if nk != k and len(nk) >= 2:
            surface_nh.setdefault(nk, Counter()).update(cnt)
    lex.surface_nh = surface_nh
    lex.root_forms = root_forms

    by_root, by_lemma, by_root_vf = {}, {}, {}
    for i, (r, l, vf) in enumerate(zip(w_root, w_lemma, w_vf)):
        by_root.setdefault(r, []).append(i)
        by_lemma.setdefault((r, l), []).append(i)
        by_root_vf.setdefault((r, vf), []).append(i)
    to_arr = lambda d: {k: np.array(v, dtype=np.int32) for k, v in d.items()}
    lex.by_root, lex.by_lemma, lex.by_root_vf = to_arr(by_root), to_arr(by_lemma), to_arr(by_root_vf)
    lex.vidx = vidx
    lex.v_sura = verses_df["sura"].to_numpy()
    order = np.argsort(lex.w_verse, kind="stable")
    bounds = np.searchsorted(lex.w_verse[order], np.arange(len(verses_df) + 1))
    lex.by_verse = [order[bounds[i]:bounds[i + 1]] for i in range(len(verses_df))]
    lex.root_by_key = {}
    for r in by_root:
        if not r.startswith("PN:"):
            lex.root_by_key.setdefault(lex_key(r), r)
    return lex


