FEATURED_TOPICS = ["الصبر على البلاء", "التوكل على الله", "بر الوالدين", "الرزق", "التوبة والاستغفار",
                   "قصة يوسف", "آية الكرسي", "الجنة ونعيمها", "أحس بضيق", "الدعاء"]
