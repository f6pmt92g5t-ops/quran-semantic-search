def _nfc(text):
    """توحيد ترتيب علامات التشكيل (Unicode NFC): "جَنَّة" قد تُكتب شدة ثم فتحة أو
    فتحة ثم شدة؛ بدون التوحيد لا تتطابق القاعدة المكتوبة يدويًا مع بيانات المعجم."""
    return unicodedata.normalize("NFC", text) if text else text


