def _verse_max(values: np.ndarray, seg_v: np.ndarray, mask: np.ndarray, n: int) -> np.ndarray:
    out = np.full(n, -np.inf, dtype=np.float32)
    np.maximum.at(out, seg_v[mask], values[mask])
    return out


def semantic_text(query: str) -> str:
    """نص الاستعلام الذي يُرمَّز دلاليًا: بدون كلمات صياغة السؤال والحشو العامي وكلمات الإطار
    ("آيات"، "حكم"، "ابي")، بشرط أن يبقى شيء. حروف المعاني الفصيحة تبقى، فالاقتباسات القرآنية
    تُرمَّز كما هي."""
    words = normalize_arabic(query).split()
    kept = [w for w in words if lex_key(w) not in SEMANTIC_DROP_KEYS]
    return " ".join(kept) if kept else " ".join(words)


# وحدة الاسترجاع (Retrieval unit): أجزاء التجويد (الافتراضي، المقاس في التقرير)، الآية كاملة، أو الاثنان معًا
UNITS = ("segment", "verse", "both")
VERSE_EMB_FILE = os.path.join(BASE_DIR, "verse_embeddings.npy")


@st.cache_resource(show_spinner="جاري تجهيز تمثيلات الآيات الكاملة (مرة واحدة فقط)...")
def load_verse_embeddings(_model, _D) -> np.ndarray:
    """متجه لكل آية كاملة بنفس النموذج. يُقرأ من verse_embeddings.npy إن وُجد، وإلا يُحسب مرة واحدة."""
    if os.path.exists(VERSE_EMB_FILE):
        e = np.load(VERSE_EMB_FILE).astype(np.float32)
    else:
        e = _model.encode([normalize_arabic(t) for t in _D.verses.text], batch_size=64,
                          convert_to_numpy=True).astype(np.float32)
    return e / np.maximum(np.linalg.norm(e, axis=1, keepdims=True), 1e-12)


def encode_query(query: str, model) -> np.ndarray:
    q = model.encode(semantic_text(query) if SEMANTIC_CLEAN else normalize_arabic(query)).astype(np.float32)
    return q / (np.linalg.norm(q) + 1e-12)


def semantic_components(query: str, model, D: SearchData, unit: str = "segment", verse_emb=None, q=None):
    """S(v) لكل آية. segment = أعلى تشابه بين السؤال وأي جزء من الآية؛ verse = تشابه السؤال مع الآية كاملة؛
    both = الأعلى من الاثنين. يرجع أيضًا تشابه كل جزء (cos) لإظهار الجزء الأقرب."""
    if q is None:
        q = encode_query(query, model)
    cos = D.emb @ q
    sem = _verse_max(cos, D.seg_v, D.prim, D.n)
    sem2 = _verse_max(cos, D.seg_v, D.second, D.n)
    if D.win_emb is not None:
        wsem = _verse_max(D.win_emb @ q - WINDOW_PENALTY, D.win_v, D.win_mask, D.n)
        sem = np.fmax(sem, wsem)          # fmax: يتجاهل NaN/-inf من جهة واحدة
    sem = np.where(np.isfinite(sem), sem, sem2)
    sem3 = _verse_max(cos - SHORT_PENALTY, D.seg_v, D.short, D.n)
    sem = np.where(np.isfinite(sem), sem, sem3)
    sem = np.where(np.isfinite(sem), sem, 0.0).astype(np.float32)
    if unit != "segment" and verse_emb is not None:
        vsem = (verse_emb @ q).astype(np.float32)
        sem = vsem if unit == "verse" else np.maximum(sem, vsem)
    return sem, cos


def best_segments(cos: np.ndarray, D: SearchData) -> np.ndarray:
    """لكل آية: رقم جزئها الأقرب إلى السؤال (أعلى تشابه)."""
    best = np.full(D.n, -1, dtype=np.int64)
    order = np.argsort(cos, kind="stable")
    best[D.seg_v[order]] = order          # الأعلى تشابهًا يُكتب أخيرًا فيبقى
    return best


def _merge_identical(df: pd.DataFrame, D: SearchData) -> pd.DataFrame:
    """آيات متطابقة نصًا (مثل "فبأي آلاء ربكما تكذبان" ×31) تُعرض مرة واحدة."""
    keys = D.text_key[df["vidx"].to_numpy()]
    first_row, others = {}, {}
    for pos, (k, s, a) in enumerate(zip(keys, df["sura"], df["aya"])):
        if k in first_row:
            others[k].append(f"{s}:{a}")
        else:
            first_row[k] = pos
            others[k] = []
    keep = sorted(first_row.values())
    out = df.iloc[keep].copy()
    out["also"] = [", ".join(others[k]) for k in keys[keep]]
    return out


def semantic_search(query: str, model, D: SearchData, sem_cos=None, unit: str = "segment",
                    verse_emb=None) -> pd.DataFrame:
    cos = None
    if sem_cos is None:
        sem, cos = semantic_components(query, model, D, unit, verse_emb)
    else:
        sem = sem_cos
    lexical, _tiers, word_tier, used = analyze_query(query, D.lex)
    score = sem + BETA_LEXICAL * lexical
    if TAFSIR_WEIGHT:
        covered = [u[0] for u in used if u[2] >= TIER_MEDIUM]
        score = score + TAFSIR_WEIGHT * tafsir_scores(query, D, covered)
    order = np.argsort(-score, kind="stable")
    sem_cut = max(REL_SEMANTIC_ABS, float(sem.max()) - REL_SEMANTIC_GAP)
    relevant = (lexical >= REL_LEXICAL_MIN) | (sem >= sem_cut)
    matched = matched_words_by_verse(word_tier, D.lex, TIER_MEDIUM)
    df = pd.DataFrame({
        "vidx": order,
        "sura": D.verses.sura.to_numpy()[order],
        "aya": D.verses.aya.to_numpy()[order],
        "text": D.verses.text.to_numpy()[order],
        "score": score[order],
        "semantic": sem[order],
        "lexical": lexical[order],
        "relevant": relevant[order],
    })
    df["matched"] = [matched.get(int(i), "") for i in order]
    if cos is not None:
        best = best_segments(cos, D)[order]
        df["seg_best"] = best
        df["seg_cos"] = np.where(best >= 0, cos[np.maximum(best, 0)], np.nan)
    return _merge_identical(df, D).reset_index(drop=True)


def text_search(query: str, D: SearchData) -> pd.DataFrame:
    lexical, tiers, word_tier, _used = analyze_query(query, D.lex)
    if tiers is None:
        return pd.DataFrame(columns=["vidx", "sura", "aya", "text", "score", "matched", "also"])
    hits = np.nonzero(lexical > 0)[0]
    words_matched = (tiers[:, hits] > 0).sum(0)
    # عند تساوي الدرجة (مثلًا كل مشتقات "استوى" قوية) تتقدم الآية التي فيها الكلمة
    # بلفظها كما كُتبت ("استويت" 23:28) بدل ترتيب المصحف فقط.
    qkeys = {_strip_article(lex_key(w)) for w in normalize_arabic(query).split()} - STOP_KEYS
    exact = np.array([len(qkeys & D.word_sets[i]) for i in hits])
    order = sorted(range(len(hits)), key=lambda j: (-round(float(lexical[hits[j]]), 6), -exact[j], hits[j]))
    idx = hits[order]
    matched = matched_words_by_verse(word_tier, D.lex, TIER_WEAK)
    df = pd.DataFrame({
        "vidx": idx,
        "sura": D.verses.sura.to_numpy()[idx],
        "aya": D.verses.aya.to_numpy()[idx],
        "text": D.verses.text.to_numpy()[idx],
        "score": lexical[idx],
        "words_matched": words_matched[order],
    })
    df["matched"] = [matched.get(int(i), "") for i in idx]
    return _merge_identical(df, D).reset_index(drop=True)


def legacy_ranking(query: str, cos: np.ndarray, D: SearchData) -> list:
    """ترتيب النسخة السابقة (v2) حرفيًا: أعلى جزء + مكافأة جذر ISRI حتى 0.5."""
    sem = _verse_max(cos, D.seg_v, D.legacy_mask, D.n)
    score = np.where(np.isfinite(sem), sem + legacy_bonus(query, D.legacy_roots, D.n), -np.inf)
    order = np.argsort(-score, kind="stable")
    return [(int(D.verses.sura[i]), int(D.verses.aya[i])) for i in order if np.isfinite(score[i])]


