    verses_per_text = pd.Series(seg_v).groupby(seg_norm.values).transform("nunique").to_numpy()
    is_formula = verses_per_text >= FORMULA_MIN_VERSES
    long_enough = word_counts >= MIN_SEGMENT_WORDS

    D.emb = embeddings / np.linalg.norm(embeddings, axis=1, keepdims=True)
    D.seg_v = seg_v
    D.seg_text = segments_df["text"].to_numpy()
    D.prim = long_enough & ~is_basmala & ~is_formula
    D.second = long_enough & ~is_basmala & is_formula
    # آيات كلها قصيرة ("ألهاكم التكاثر" 102:1، "والشمس وضحاها" 91:1): أجزاؤها أقل من 3 كلمات
    # فكانت خارج الفهرس الدلالي تمامًا (تشابه = 0). تُستخدم فقط إذا لم يكن للآية غيرها.
    D.short = ~long_enough & ~is_basmala
    # النوافذ (انظر make_windows): اختيارية — إذا لم يوجد الملف يعمل البحث بالأجزاء فقط.
    D.win_emb = None
    win_path = os.path.join(BASE_DIR, "window_embeddings.npy")
    if os.path.exists(win_path):
        windows = make_windows(segments_df)
        win_emb = np.load(win_path).astype(np.float32)
        if len(windows) != win_emb.shape[0]:
            raise ValueError(f"window_embeddings.npy has {win_emb.shape[0]} rows but segments.csv gives "
                             f"{len(windows)} windows — regenerate it (window experiment, report Section 5.3.3).")
        wseg = windows["segment"].to_numpy()
        D.win_emb = win_emb / np.linalg.norm(win_emb, axis=1, keepdims=True)
        D.win_v = seg_v[wseg]
        D.win_mask = D.prim[wseg]        # نوافذ الأجزاء الأساسية فقط (لا بسملة ولا عبارات متكررة)
    D.legacy_mask = long_enough            # v2 behaviour (for the evaluation tab)
    D.n = n

    D.lex = build_lexicon(D.verses)
    D.legacy_roots = legacy_build_root_index(D.verses["text_original"])
    D.text_key = D.verses["text"].apply(lex_key).to_numpy()   # لدمج الآيات المتطابقة نصًا
    # كلمات كل آية بعد التوحيد وحذف السوابق: لترتيب "الكلمة نفسها أولًا" في البحث النصي
    D.word_sets = [{_strip_article(lex_key(w)) for w in t.split()} for t in D.verses["text"]]
    D.vidx = vidx
    add_reader_data(D, vidx)
    return D


